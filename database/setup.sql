create table if not exists public.sc_users(
 id bigint generated by default as identity primary key,
 username text not null unique check (length(username) between 3 and 30),
 name text not null, salt text not null,password_hash text not null,
 recovery_hash text, role text not null default 'student' check (role in ('student','teacher','admin')),
 active boolean not null default true
);
create table if not exists public.sc_sessions(
 token_hash text primary key, user_id bigint not null references public.sc_users(id) on delete cascade, expires bigint not null
);
create index if not exists sc_sessions_user on public.sc_sessions(user_id);
create table if not exists public.sc_progress(
 user_id bigint primary key references public.sc_users(id) on delete cascade,
 progress jsonb not null, revision integer not null default 1
);
create table if not exists public.sc_teacher_exams(
 id uuid primary key,owner bigint not null references public.sc_users(id) on delete cascade,
 title text not null,subject text not null,grade integer not null,count integer not null,
 body jsonb not null,revision integer not null default 1,created bigint not null, updated bigint not null
);
create index if not exists sc_teacher_exams_owner on public.sc_teacher_exams(owner,updated desc);
-- Deny browser-facing public access. Only the server-side service_role API key may access tables.
alter table public.sc_users enable row level security;
alter table public.sc_sessions enable row level security;
alter table public.sc_progress enable row level security;
alter table public.sc_teacher_exams enable row level security;
revoke all on public.sc_users,public.sc_sessions,public.sc_progress,public.sc_teacher_exams from anon,authenticated;
revoke all on sequence public.sc_users_id_seq from anon,authenticated;
